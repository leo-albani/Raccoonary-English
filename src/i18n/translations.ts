export const RTL_LANGUAGES = ['ar', 'he', 'fa', 'ur'];

export function isRTLLanguage(langCode?: string): boolean {
  if (!langCode) return false;
  return RTL_LANGUAGES.includes(langCode.toLowerCase());
}

/**
 * Get translated text for a key with parameter replacement and fallback to Italian.
 */
export function getTranslation(
  key: string,
  translationsMap?: Record<string, string> | null,
  params?: Record<string, string | number>
): string {
  let text = translationsMap?.[key] || IT_TRANSLATIONS[key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, paramValue]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
    });
  }

  return text;
}
